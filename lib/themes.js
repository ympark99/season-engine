const clip = v => Math.max(-0.7, Math.min(2, v));
export const ROT_OFF = [15, 10, 5, 0];          // 3주 전 · 2주 전 · 1주 전 · 오늘 (거래일)

/**
 * 섹터 순환 재료 — 종목별 [60일 수익, 최근 20일 수익, 그 전 20일 수익] × 4개 시점.
 * 섹터 평균·4분면 좌표는 화면에서 계산한다 (네가 섹터를 바꾸면 바로 다시 그려지게).
 * items: { code, name, s: Series, season: Int8Array }
 */
export function rotationOf(items, thMap = {}) {
  const cnt = new Map();
  for (const x of items) { const d = x.s.d; if (d.length) cnt.set(d[d.length - 1], (cnt.get(d[d.length - 1]) || 0) + 1); }
  const D0 = [...cnt.entries()].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? 1 : -1))[0]?.[0];       // 가장 많은 종목의 마지막 봉
  if (!D0) return null;
  const mem = [], U = ROT_OFF.map(() => [0, 0, 0]);
  let dates = null;
  for (const x of items) {
    const p = x.s.p, n = p.length;
    let i = n - 1;
    while (i > n - 6 && i > 0 && x.s.d[i] > D0) i--;                                   // 하루 더 받은 종목(새로 채운 일봉 등)도 같은 날짜 기준으로 맞춘다
    if (x.s.d[i] !== D0 || i < 60 + 15 + 1) continue;
    if (!dates) dates = ROT_OFF.map(o => x.s.d[i - o]);
    const v = ROT_OFF.map(o => { const t = i - o; return [clip(p[t] / p[t - 60] - 1), clip(p[t] / p[t - 20] - 1), clip(p[t - 20] / p[t - 40] - 1)].map(z => +(100 * z).toFixed(2)); });
    v.forEach((r, k) => { U[k][0] += r[0]; U[k][1] += r[1]; U[k][2] += r[2]; });
    mem.push({ c: x.code, n: x.name, s: x.season[i], th: thMap[x.code] || '기타', v });
  }
  if (mem.length < 20) return null;
  return { asof: D0, dates, n: mem.length, U: U.map(r => r.map(z => +(z / mem.length).toFixed(2))), mem, at: new Date().toISOString() };
}
